const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(require('node:path').join(__dirname, '../extension/app.js'), 'utf8');
const context = vm.createContext({});
vm.runInContext(source.split('// CARD ORDER MODEL:')[1].split('\n').slice(1).join('\n').split('// END CARD ORDER MODEL')[0], context);
const groups = [{domain:'x',tabs:[1]}, {domain:'bilibili',tabs:[1,2,3,4]}, {domain:'youtube',tabs:[1,2]}];
const ids = state => Array.from(context.sortDomainCards(groups,state), g=>g.domain);
let state;
assert.deepEqual(ids(state), ['bilibili','youtube','x']);
state=context.changeCardOrder(groups,state,'swap','x','youtube');
assert.deepEqual(ids(state), ['bilibili','x','youtube']);
state=context.changeCardOrder(groups,state,'top','youtube');
assert.deepEqual(ids(state), ['youtube','bilibili','x']);
state=context.changeCardOrder(groups,state,'bottom','bilibili');
assert.deepEqual(ids(state), ['youtube','x','bilibili']);
const fresh=[...groups,{domain:'new',tabs:Array(10).fill(1)}];
assert.deepEqual(Array.from(context.sortDomainCards(fresh,state),g=>g.domain), ['youtube','x','new','bilibili']);
state=context.changeCardOrder(groups,state,'swap','youtube','bilibili');
assert.deepEqual(ids(state), ['bilibili','x','youtube']);
assert.deepEqual(ids(JSON.parse(JSON.stringify(state))),ids(state));
assert.deepEqual(ids(context.changeCardOrder(groups,state,'swap','missing','x')),ids(state));
assert.deepEqual(ids(context.changeCardOrder(groups,state,'reset')),['bilibili','youtube','x']);
assert.deepEqual(ids({order:[null,'x','x',3],top:'bad',bottom:['x','x']}),['bilibili','youtube','x']);
assert.deepEqual(Array.from(context.sortDomainCards(groups.filter(g=>g.domain!=='bilibili'),state),g=>g.domain),['x','youtube']);
console.log('Card ordering: default counts, swaps, top/bottom, new/reopened groups, persistence, reset and invalid data passed');
